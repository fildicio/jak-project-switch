#!/usr/bin/env python3
"""Generate the GL time-split wrapper header (deko3d migration P0.5). (AI-assisted)

DEKO3D_MIGRATION_PLAN.md P0.5 asks for the go/no-go number: how much of the
Switch render phase is spent inside GL entry points (Mesa+nouveau driver time)
vs. the game's own C++ (matrix math, bucket walking, memcpy). If GL time
dominates, porting the submit path to deko3d can pay for 30 fps at stock
clocks; if the game's own C++ dominates, it cannot, and the migration should
stop before Phase 2.

Measurement mechanism: glad (`third-party/glad/include/glad/glad.h`) defines
every GL entry point as a macro `#define glXxx glad_glXxx` pointing at a
function pointer. This script parses those typedefs and emits, for every
function the game actually calls (the list in `docs/deko3d/gl-inventory.json`,
117 as of writing), an `#undef` plus an inline wrapper with the *exact same
signature* that:

  - calls straight through when the render-phase recorder is off (default,
    and permanently off unless the `gk_glt.txt` kill-switch file exists), so
    the non-measuring build is behaviorally identical and costs one branch;
  - when recording, brackets the call with `cntvct_el0` reads and
    accumulates ticks into a per-function counter.

The wrappers live in a header included right after glad.h in
`game/graphics/pipelines/opengl.h`, so every TU in game/graphics that talks
to GL goes through them. The runtime half is
`game/graphics/opengl_renderer/gl_time_split.{h,cpp}` (hand-written).

The generated IDs are ordered by inventory call count (descending) and are
NOT stable across regenerations -- never persist them.

Usage:
  python3 scripts/gen-gl-time-split.py            # write the header
  python3 scripts/gen-gl-time-split.py --check    # verify it is up to date
"""

import argparse
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GLAD_H = REPO / "third-party" / "glad" / "include" / "glad" / "glad.h"
INVENTORY = REPO / "docs" / "deko3d" / "gl-inventory.json"
OUT = REPO / "game" / "graphics" / "opengl_renderer" / "gl_time_split_funcs.h"

TYPEDEF_RE = re.compile(
    r"^typedef\s+(.+?)\s+\(APIENTRYP\s+PFN(\w+?)PROC\)\s*\((.*?)\);\s*$")


def parse_glad():
    """Return {UpperName: (return_type, [param strings])} for every glad typedef."""
    funcs = {}
    for line in GLAD_H.read_text().splitlines():
        m = TYPEDEF_RE.match(line.strip())
        if not m:
            continue
        ret, upper, params = m.group(1), m.group(2), m.group(3).strip()
        funcs[upper] = (ret, split_params(params))
    return funcs


def split_params(params):
    if params in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def param_name(p):
    """Last identifier of a parameter declaration ('GLenum target' -> 'target')."""
    toks = re.findall(r"[A-Za-z_]\w*", p)
    return toks[-1] if toks else "_"


def make_wrapper(name, glad_name, ret, params):
    args = ", ".join(params)
    argnames = ", ".join(param_name(p) for p in params)
    call = f"{glad_name}({argnames})"
    if ret == "void":
        passthrough = f"{call};\n    return;"
        timed_call = call
        tail = "glt::add(GLT_ID_{}, glt::now() - glt_t0);".format(name)
    else:
        passthrough = f"return {call};"
        timed_call = f"const auto glt_r = {call}"
        tail = "glt::add(GLT_ID_{}, glt::now() - glt_t0);\n  return glt_r;".format(name)
    return f"""#undef {name}
inline {ret} {name}({args}) {{
  if (!glt::recording()) {{
    {passthrough}
  }}
  const uint64_t glt_t0 = glt::now();
  {timed_call};
  {tail}
}}"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the header is not up to date")
    args = ap.parse_args()

    glad = parse_glad()
    inventory = json.loads(INVENTORY.read_text())
    # functions the game actually calls, most-used first (IDs ordered by this)
    called = sorted(inventory["functions"].items(), key=lambda kv: -kv[1])

    missing = []
    chunks = []
    for name, count in called:
        upper = name.upper()
        if upper not in glad:
            missing.append(name)
            continue
        ret, params = glad[upper]
        glad_name = f"glad_{name}"
        chunks.append(make_wrapper(name, glad_name, ret, params))
    if missing:
        raise SystemExit(f"glad.h has no typedef for: {', '.join(missing)}")

    header = f"""// GENERATED by scripts/gen-gl-time-split.py -- DO NOT EDIT. (AI-assisted)
// Source of truth: third-party/glad/include/glad/glad.h typedefs + the called
// function list in docs/deko3d/gl-inventory.json ({len(called)} functions).
// IDs are ordered by inventory call count and are NOT stable -- never persist.
#pragma once

#include "third-party/glad/include/glad/glad.h"
#include "game/graphics/opengl_renderer/gl_time_split.h"

namespace glt {{
constexpr int kFuncCount = {len(called)};

// per-function tick/call accumulators; written only on the recording thread,
// zeroed by end_render_phase() each frame (interval copies live in the .cpp).
extern uint64_t g_ticks[kFuncCount];
extern uint32_t g_calls[kFuncCount];

// function names, index-aligned with the GLT_ID_* constants (for reports)
constexpr const char* kNames[kFuncCount] = {{
{chr(10).join(f'    "{name}",' for name, _ in called)}
}};

inline void add(int id, uint64_t dt) {{
  g_ticks[id] += dt;
  g_calls[id]++;
}}
}}  // namespace glt

// glad defines each GL entry point as a macro pointing at its glad_ function
// pointer. Replace the macro with an inline wrapper of the exact same
// signature that times the call while the render phase is recording. When
// recording is off (the default, and forever without the gk_glt.txt
// kill-switch file) this is a passthrough with one branch.
{chr(10).join(f"constexpr int GLT_ID_{name} = {i};" for i, (name, _) in enumerate(called))}

{chr(10).join(chunks)}
"""

    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != header:
            print(f"{OUT.relative_to(REPO)} is out of date; regenerate it")
            return 1
        print(f"{OUT.relative_to(REPO)} up to date ({len(called)} wrappers)")
        return 0
    OUT.write_text(header)
    print(f"wrote {OUT.relative_to(REPO)}: {len(called)} wrappers")


if __name__ == "__main__":
    raise SystemExit(main())
