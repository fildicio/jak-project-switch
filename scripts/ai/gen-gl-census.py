#!/usr/bin/env python3
"""Generate game/graphics/deko3d_renderer/dk_gl_census.cpp (AI-assisted).

On the deko3d path there is no GL context and glad is never loaded, so every
glad_gl* pointer is NULL and any GL call crashes. The census installs a stub in
EVERY glad pointer: the stub does nothing, returns 0, and logs the function name the
first time it is called. One hardware run then lists exactly which GL calls the
Loader reaches on the dk path (= the seams still to write).

AArch64 note: the stubs take no parameters and return uintptr_t 0. Callers pass args
in registers / on their own stack frame and the callee ignores them, so calling
through a cast pointer is safe on AAPCS64 for every GL signature (no struct returns
in GL; float-returning GL entry points do not exist in glad's core/ES set).

Usage: scripts/ai/gen-gl-census.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GLAD = ROOT / "third-party/glad/include/glad/glad.h"
OUT = ROOT / "game/graphics/deko3d_renderer/dk_gl_census.cpp"

PAT = re.compile(r"^GLAPI (PFN[A-Z0-9_]+PROC) (glad_gl[A-Za-z0-9_]+);$", re.M)


def render() -> str:
    pairs = PAT.findall(GLAD.read_text())
    assert len(pairs) > 100, "glad.h parse failed"
    n = len(pairs)
    names = ",\n".join(f'    "{p[1][5:]}"' for p in pairs)
    sets = "\n".join(
        f"  {ptr} = reinterpret_cast<{typ}>(reinterpret_cast<void*>(&stub<{i}>));" for i, (typ, ptr) in enumerate(pairs)
    )
    return f"""// GENERATED by scripts/ai/gen-gl-census.py — do not edit by hand. (AI-assisted)
// dk-path GL census: see the script docstring for why this exists.
#include "game/graphics/deko3d_renderer/dk_gl_census.h"

#if defined(__SWITCH__)

#include <atomic>
#include <cstdint>

#include "third-party/glad/include/glad/glad.h"

// run_log.h cannot be included next to <switch.h> (u128 collision); same hand
// declaration as dk_texture_gpu.cpp.
void switch_run_logf(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

namespace dkglcensus {{
namespace {{
constexpr int kCount = {n};
const char* const kNames[kCount] = {{
{names}
}};
std::atomic<bool> s_seen[kCount];
std::atomic<uint32_t> s_distinct{{0}};

template <int I>
uintptr_t stub() {{
  if (!s_seen[I].exchange(true, std::memory_order_relaxed)) {{
    const uint32_t k = s_distinct.fetch_add(1, std::memory_order_relaxed) + 1;
    switch_run_logf("[dk] gl-census #%u first call: %s", k, kNames[I]);
  }}
  return 0;
}}
}}  // namespace

void install() {{
{sets}
  switch_run_logf("[dk] gl-census installed: %d glad pointers -> no-op stubs", kCount);
}}

uint32_t distinct_calls() {{
  return s_distinct.load(std::memory_order_relaxed);
}}
}}  // namespace dkglcensus

#endif  // __SWITCH__
"""


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("gl-census: up to date" if ok else "gl-census: STALE, re-run the script")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
