#!/usr/bin/env python3
"""Generate game/graphics/deko3d_renderer/PipelineTable.inc from
docs/deko3d/pipeline_table.json (T15, AI-assisted).

Maps every pipeline/sampler field to the T14 dkpipe:: enum names. Any value that
is not in the allowed maps is printed and exits 1 (never silently defaulted).
Run ``--check`` to regenerate in memory and exit 1 if the output differs from the
committed .inc (used by the build/CIs to detect a stale table).
"""
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
JSON_PATH = REPO_ROOT / "docs" / "deko3d" / "pipeline_table.json"
OUT_PATH = REPO_ROOT / "game" / "graphics" / "deko3d_renderer" / "PipelineTable.inc"

# depth_test OFF (depthTestEnable false) -> Always, otherwise map depthCompareOp.
COMPARE = {"Always": "Always", "Gequal": "Gequal", "Greater": "Greater", "Never": "Never"}
# top-level blend name -> dkpipe::Blend value.
BLEND = {
    "OFF": "Off",
    "STD_ALPHA": "StdAlpha",
    "PREMULT_ADD": "PremulAdd",
    "FIX128_ADD": "Fix128Add",
    "FIX64_SUB": "Fix64Sub",
    "SRC_ALPHA_SUB": "SrcAlphaSub",
    "DST_ALPHA_ADD": "DstAlphaAdd",
}
# sampler wrap / filter values in the JSON deko3d block -> dkpipe:: enum values.
WRAP = {"Repeat": "Repeat", "ClampToEdge": "ClampToEdge"}
FILTER = {"Nearest": "Nearest", "Linear": "Linear"}


def die(msg):
    print("gen-dk-pipeline-table: " + msg, file=sys.stderr)
    sys.exit(1)


def map_enum(table, value, context):
    if value not in table:
        die("%s: unknown value %r (allowed: %s)" % (context, value, ", ".join(sorted(table))))
    return table[value]


def gen_pipeline(p):
    deko = p["deko3d_state"]
    if deko["depthTestEnable"]:
        if deko["depthCompareOp"] is None:
            die("%s: depthTestEnable true but depthCompareOp null" % p["id"])
        depth_op = map_enum(COMPARE, deko["depthCompareOp"], p["id"] + ".depthCompareOp")
    else:
        depth_op = "Always"
    blend = map_enum(BLEND, p["blend"], p["id"] + ".blend")
    depth_test = "true" if deko["depthTestEnable"] else "false"
    depth_write = "true" if deko["depthWriteEnable"] else "false"
    return (
        '    {"%s", %s, dkpipe::Compare::%s, %s, dkpipe::Blend::%s},\n'
        % (p["id"], depth_test, depth_op, depth_write, blend)
    )


def gen_sampler(s):
    deko = s["deko3d"]
    wrap_u = map_enum(WRAP, deko["wrapU"], "sampler%d.wrapU" % s["index"])
    wrap_v = map_enum(WRAP, deko["wrapV"], "sampler%d.wrapV" % s["index"])
    # The `filt` axis decides min/mag DkFilter (Nearest|Linear); the mipmap bool
    # is carried separately in SamplerDesc and recombined into DkMipFilter in T16.
    min_f = "Linear" if s["filt"] else "Nearest"
    mag_f = "Linear" if s["filt"] else "Nearest"
    mipmap = "true" if s["mipmap"] else "false"
    return (
        "    {%d, dkpipe::Wrap::%s, dkpipe::Wrap::%s, dkpipe::Filter::%s, "
        "dkpipe::Filter::%s, %s},\n"
        % (s["index"], wrap_u, wrap_v, min_f, mag_f, mipmap)
    )


def build(doc):
    out = [
        "// Generated by scripts/gen-dk-pipeline-table.py from docs/deko3d/pipeline_table.json.\n",
        "// Do not edit. (AI-assisted)\n",
        "static const dkpipe::PipelineDesc kPipelines[] = {\n",
    ]
    for p in doc["pipelines"]:
        out.append(gen_pipeline(p))
    out.append("};\n")
    out.append("static const dkpipe::SamplerDesc kSamplers[] = {\n")
    for s in doc["samplers"]:
        out.append(gen_sampler(s))
    out.append("};\n")
    n_p = len(doc["pipelines"])
    n_s = len(doc["samplers"])
    if n_p != doc["pipeline_count"] or n_s != doc["sampler_count"]:
        die(
            "count mismatch: pipelines %d/%d, samplers %d/%d"
            % (n_p, doc["pipeline_count"], n_s, doc["sampler_count"])
        )
    out.append('static_assert(sizeof(kPipelines) / sizeof(kPipelines[0]) == %d, "count");\n' % n_p)
    out.append('static_assert(sizeof(kSamplers) / sizeof(kSamplers[0]) == %d, "count");\n' % n_s)
    return "".join(out)


def main():
    doc = json.loads(JSON_PATH.read_text())
    expected = build(doc)
    if "--check" in sys.argv:
        actual = OUT_PATH.read_text()
        if actual != expected:
            print("gen-dk-pipeline-table: PipelineTable.inc is out of date; regenerate it.", file=sys.stderr)
            sys.exit(1)
    else:
        OUT_PATH.write_text(expected)
        print("Wrote %s (%d pipelines, %d samplers)" % (OUT_PATH, len(doc["pipelines"]), len(doc["samplers"])))


if __name__ == "__main__":
    main()
